"""Render and install a valid LocalBachelor systemd system unit.

Fixup 0.4: ``deploy/local-bachelor.service`` is a reference template
(placeholder paths, user-unit ``%h`` spec). This script generates a valid
SYSTEM unit for the host it runs on:

- ``WorkingDirectory`` = the repo root (relative ``db_path``/``data_dir`` in
  ``config.yaml`` resolve against it; architecture.md §15)
- ``ExecStart`` = the venv's python + ``-m app.main --config <abs path>``
  (mirrors the real CLI in ``app/main.py`` exactly)
- ``User``/``Group`` = the invoking non-root user, or ``--user <name>`` for
  a dedicated account
- ``WantedBy`` = ``multi-user.target``
- No secrets: the bootstrap keys live in the gitignored ``config.yaml``

The unit is installed to ``/etc/systemd/system/<name>.service`` (needs
root). The script NEVER runs systemctl itself unless ``--apply`` is given:
after installing it prints the exact daemon-reload / enable --now commands.

Usage (run with the venv's python when possible):

  .venv/bin/python scripts/install_systemd.py --dry-run
  sudo .venv/bin/python scripts/install_systemd.py
  sudo .venv/bin/python scripts/install_systemd.py --user localbachelor --apply
"""

import argparse
import getpass
import os
import re
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
UNIT_DIR = Path("/etc/systemd/system")
DEFAULT_UNIT_NAME = "local-bachelor"

# systemd unit names: no control chars, slashes, leading dots, or double
# colons (systemd.unit(5)). This stricter class also blocks path traversal
# via --name and any injection of extra unit directives.
_UNIT_NAME_RE = re.compile(r"^[A-Za-z0-9](?:[A-Za-z0-9_.-]*[A-Za-z0-9])?$")
# POSIX user/group names: also blocks directive injection via --user.
_USER_RE = re.compile(r"^[A-Za-z0-9_.-]+$")


def render_unit(
    *,
    repo_root: str,
    python: str,
    config_path: str,
    user: str | None = None,
) -> str:
    """Render the systemd unit file as text.

    Pure — no filesystem, environment, or network access; every value is an
    argument, so the result is deterministic and unit-testable. The paths
    MUST already be absolute (system units have no ``%h`` and systemd does
    not expand relative paths).
    """
    service = ["Type=simple"]
    if user is not None:
        service += [f"User={user}", f"Group={user}"]
    service += [
        f"WorkingDirectory={repo_root}",
        # JSON log level read by app/core/logging.py (default INFO).
        "Environment=LOG_LEVEL=info",
        # Real CLI entrypoint from app/main.py — keep it a plain one-liner.
        f"ExecStart={python} -m app.main --config {config_path}",
        "Restart=on-failure",
        "RestartSec=5",
    ]
    return "\n".join(
        [
            "# LocalBachelor systemd unit (roadmap task 0.4; architecture.md §15).",
            "#",
            "# Generated by scripts/install_systemd.py — do not edit by hand;",
            "# re-run the script (with --force) to regenerate it.",
            "#",
            "# This file contains NO secrets: the two bootstrap keys",
            "# (secret_key, settings_key) live in the gitignored config.yaml.",
            "#",
            "# Single process: FastAPI app + in-process job worker (SQLite in",
            "# data_dir, WAL mode). No separate worker service in v1.",
            "",
            "[Unit]",
            "Description=LocalBachelor (local-first RAG research assistant)",
            "After=network.target",
            "",
            "[Service]",
            *service,
            "",
            "[Install]",
            "WantedBy=multi-user.target",
            "",
        ]
    )


def resolve_venv_python(repo_root: Path) -> str:
    """Pick the interpreter the unit's ExecStart should run.

    Primary: the interpreter running this script (``sys.executable``) when it
    lives inside the repo venv. Fallback: the repo venv's python, so that an
    invocation with the system interpreter still yields a working unit. Last
    resort: ``sys.executable``.
    """
    venv_dir = repo_root / ".venv"
    try:
        if Path(sys.executable).resolve().is_relative_to(venv_dir):
            return sys.executable
    except OSError:
        pass
    for candidate in (
        venv_dir / "bin" / "python",
        venv_dir / "Scripts" / "python.exe",
    ):
        if candidate.is_file():
            return str(candidate)
    return sys.executable


def resolve_service_user() -> str | None:
    """Default ``User=``/``Group=``: the invoking NON-ROOT user.

    Sudo-aware: under sudo the original user is in ``SUDO_USER``. Returns
    ``None`` when only root is known (the caller warns; the rendered unit
    then omits User=/Group= and runs as root).
    """
    sudo_user = os.environ.get("SUDO_USER", "").strip()
    if sudo_user and sudo_user != "root":
        return sudo_user
    euid = os.geteuid() if hasattr(os, "geteuid") else None
    if euid == 0:
        return None
    return getpass.getuser()


def main(argv: list[str] | None = None, *, unit_dir: Path = UNIT_DIR) -> int:
    """CLI entry point. Returns the process exit code.

    ``unit_dir`` is a testability seam: production always installs under
    ``/etc/systemd/system``; tests point it at a temp directory.
    """
    parser = argparse.ArgumentParser(
        prog="install_systemd.py",
        description=(
            "Render and install a valid LocalBachelor systemd system unit "
            "to /etc/systemd/system/<name>.service. Prints the exact "
            "daemon-reload / enable --now commands after installing; runs "
            "them only with --apply."
        ),
        epilog=(
            "examples:\n"
            "  .venv/bin/python scripts/install_systemd.py --dry-run\n"
            "  sudo .venv/bin/python scripts/install_systemd.py\n"
            "  sudo .venv/bin/python scripts/install_systemd.py "
            "--user localbachelor --apply\n"
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument(
        "--name",
        default=DEFAULT_UNIT_NAME,
        help=f"unit name (default: {DEFAULT_UNIT_NAME})",
    )
    parser.add_argument(
        "--user",
        help="user/group the service runs as (default: the invoking "
        "non-root user)",
    )
    parser.add_argument(
        "--dry-run",
        action="store_true",
        help="print the rendered unit; write nothing",
    )
    parser.add_argument(
        "--force",
        action="store_true",
        help="overwrite an existing unit file",
    )
    parser.add_argument(
        "--apply",
        action="store_true",
        help="after installing, run systemctl daemon-reload and enable --now",
    )
    args = parser.parse_args(argv)

    if not _UNIT_NAME_RE.fullmatch(args.name):
        print(
            f"error: invalid --name {args.name!r}: allowed characters are "
            "A-Z a-z 0-9 ':' '_' '.' '-' (systemd unit name rules).",
            file=sys.stderr,
        )
        return 2
    if args.user is not None and not _USER_RE.fullmatch(args.user):
        print(
            f"error: invalid --user {args.user!r}: allowed characters are "
            "A-Z a-z 0-9 '_' '.' '-' (POSIX name rules).",
            file=sys.stderr,
        )
        return 2

    repo_root = REPO_ROOT
    python = resolve_venv_python(repo_root)
    config_path = str(repo_root / "config.yaml")
    if not (repo_root / "config.yaml").exists():
        print(
            "warning: no config.yaml in the repo root — the service will "
            "fail to start until you create it (copy config.example.yaml) "
            "and run `alembic upgrade head`."
        )

    if args.user is not None:
        user: str | None = args.user
    else:
        user = resolve_service_user()
        if user is None:
            print(
                "note: invoked as root without --user and without SUDO_USER: "
                "the unit will run as root. Prefer a dedicated unprivileged "
                "account, e.g. --user localbachelor."
            )

    unit_text = render_unit(
        repo_root=str(repo_root),
        python=python,
        config_path=config_path,
        user=user,
    )

    if args.dry_run:
        print(unit_text)
        return 0

    target = unit_dir / f"{args.name}.service"
    if target.exists() and not args.force:
        print(
            f"error: {target} already exists — refusing to overwrite. "
            f"Re-run with --force to replace it.",
            file=sys.stderr,
        )
        return 1
    try:
        target.write_text(unit_text, encoding="utf-8")
        os.chmod(target, 0o644)
    except OSError as exc:
        print(
            f"error: cannot write {target}: {exc}\n"
            f"Re-run as root, e.g.:\n"
            f"  sudo {python} {Path(__file__).resolve()}",
            file=sys.stderr,
        )
        return 1
    print(f"installed {target}")

    reload_cmd = "systemctl daemon-reload"
    enable_cmd = f"systemctl enable --now {args.name}.service"
    if args.apply:
        for parts in (
            ["systemctl", "daemon-reload"],
            ["systemctl", "enable", "--now", f"{args.name}.service"],
        ):
            try:
                subprocess.run(parts, check=True)
            except (OSError, subprocess.CalledProcessError) as exc:
                print(f"error: {' '.join(parts)} failed: {exc}", file=sys.stderr)
                return 1
        print(f"{args.name}.service is enabled and running.")
    else:
        print("Next steps (run these now, or re-run this script with --apply):")
        print(f"  sudo {reload_cmd}")
        print(f"  sudo {enable_cmd}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
